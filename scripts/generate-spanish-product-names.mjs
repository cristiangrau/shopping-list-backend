import { readFile, writeFile } from 'node:fs/promises';

const [sourcePath, outputPath] = process.argv.slice(2);
if (!sourcePath || !outputPath) {
  console.error('Usage: node scripts/generate-spanish-product-names.mjs <categories_es.json> <output.sql>');
  process.exit(1);
}

const source = JSON.parse(await readFile(sourcePath, 'utf8'));
const products = new Map();

function collect(categories) {
  for (const category of categories ?? []) {
    for (const product of category.products ?? []) {
      if (product?.id != null && product?.display_name) {
        products.set(String(product.id), String(product.display_name));
      }
    }
    collect(category.categories);
  }
}

collect(source.results);

const sqlString = (value) => `'${value.replaceAll("'", "''")}'`;
const values = [...products.entries()]
  .sort(([left], [right]) => left.localeCompare(right, undefined, { numeric: true }))
  .map(([id, name]) => `    (${sqlString(id)}, ${sqlString(name)})`)
  .join(',\n');

const sql = `-- Generated by scripts/generate-spanish-product-names.mjs
-- Source product IDs are joined directly to catalog.products.id.
BEGIN;

ALTER TABLE catalog.products
    ADD COLUMN IF NOT EXISTS display_name_es TEXT;

UPDATE catalog.products AS product
SET display_name_es = source.display_name_es
FROM (
    VALUES
${values}
) AS source(id, display_name_es)
WHERE product.id = source.id
  AND product.display_name_es IS DISTINCT FROM source.display_name_es;

COMMIT;
`;

await writeFile(outputPath, sql);
console.log(`Generated ${outputPath} with ${products.size} Spanish product names.`);
